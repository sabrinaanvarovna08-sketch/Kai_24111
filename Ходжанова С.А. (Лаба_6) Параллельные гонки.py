import asyncio


async def racer(name, delay):
    """
    Асинхронная функция, имитирующая бег гонщика.
    Принимает имя гонщика (name) и время задержки (delay).
    """
    # Имитация бега: асинхронная пауза на указанное количество секунд
    await asyncio.sleep(delay)

    # Вывод сообщения о финише
    print(f"{name} финишировал!")


async def main():
    # Создаем двух гонщиков и запускаем их одновременно с помощью asyncio.gather
    # Молния бежит 2 секунды, Стрела — 2.5 секунды
    await asyncio.gather(
        racer("Молния", 2),
        racer("Стрела", 2.5)
    )


if __name__ == "__main__":
    # Запуск асинхронной программы
    asyncio.run(main())

