import asyncio


async def long_running_task():
    """
    1. Корутина, имитирующая долгую операцию.
    """
    print("Фоновая задача начала работу...")
    # Ждем 5 секунд
    await asyncio.sleep(5)
    print("Фоновая задача завершена.")


async def main():
    """
    2. Главная функция, которая запускает фоновую задачу
    и продолжает свою работу.
    """
    # Запускаем фоновую задачу с помощью asyncio.create_task()
    # Она начинает выполняться сразу, но мы не ждем её завершения здесь
    task = asyncio.create_task(long_running_task())

    # 3. Сразу после запуска фоновой задачи продолжаем работу
    print("Основная программа продолжает работу...")

    # Выполняем цикл 3 раза с интервалом в 1 секунду
    for i in range(3):
        await asyncio.sleep(1)
        print("Основная программа работает...")

    # 4. Ожидаем завершения фоновой задачи, чтобы программа
    # не закрылась раньше времени и мы увидели финальное сообщение.
    # (Так как фоновая задача спит 5 секунд, а цикл занял 3 секунды,
    # нам осталось подождать еще 2 секунды).
    await task


if __name__ == "__main__":
    # Запуск асинхронной программы
    asyncio.run(main())